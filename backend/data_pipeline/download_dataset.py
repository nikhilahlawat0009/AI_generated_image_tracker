"""
Dataset Downloader
==================

Downloads the CIFAKE dataset from HuggingFace.

WHAT IS CIFAKE:
  A peer-reviewed dataset of 120,000 images:
    - 60,000 real images (CIFAR-10, real photographs)
    - 60,000 AI-generated equivalents (Stable Diffusion v1.4)

  Paper: "CIFAKE: Image Classification and Explainable Identification
          of AI-Generated Synthetic Images" (Bird & Lotfi, 2023)

WHY THIS DATASET (interview answer):
  "I chose CIFAKE because it's balanced (1:1 ratio), peer-reviewed,
   and has a known generation process (SD v1.4), which lets me analyze
   per-generator performance. I then supplemented it with images from
   newer generators to test for distribution shift."

LIMITATION TO ACKNOWLEDGE (shows maturity):
  CIFAKE uses 32x32 images — low resolution. Real-world AI images are
  512x512 or higher. The frequency artifacts we detect may differ at
  higher resolution. I note this as a known limitation and planned
  to add higher-resolution data in the next iteration.

Run:
  python download_dataset.py --output ./raw_data --samples 5000
"""

import argparse
import os
from pathlib import Path


def download_cifake(output_dir: Path, max_samples_per_class: int = 5000):
    """
    Downloads CIFAKE subset via HuggingFace datasets library.
    Uses streaming to avoid loading 120k images into RAM at once.
    """
    try:
        from datasets import load_dataset
        from PIL import Image as PILImage
    except ImportError:
        print("Run: pip install datasets Pillow")
        return

    print(f"Downloading CIFAKE (up to {max_samples_per_class} per class)...")
    print("This uses HuggingFace streaming — no full 1.4GB download needed.\n")

    # Load dataset in streaming mode
    # WHY STREAMING: We don't need all 120k images. Taking a stratified
    # sample of 5k per class is enough for fine-tuning a ViT head.
    # Streaming avoids a 1.4GB download.
    # dragonintelligence/CIFAKE-image-dataset is the stable mirror of the
    # original CIFAKE dataset (Bird & Lotfi, 2023). Labels: 0=FAKE, 1=REAL.
    ds = load_dataset("dragonintelligence/CIFAKE-image-dataset", streaming=True)

    real_dir = output_dir / "real"
    ai_dir   = output_dir / "ai_generated"
    real_dir.mkdir(parents=True, exist_ok=True)
    ai_dir.mkdir(parents=True, exist_ok=True)

    real_count = 0
    ai_count   = 0
    total_needed = max_samples_per_class * 2

    split = ds.get("train", ds.get("all"))
    if split is None:
        print("[!] Could not find a valid split in the dataset.")
        return

    for i, example in enumerate(split):
        if real_count >= max_samples_per_class and ai_count >= max_samples_per_class:
            break

        label = example.get("label", example.get("labels"))
        img   = example.get("image", example.get("img"))

        if img is None:
            continue

        # CIFAKE label mapping — verified by inspecting dataset features:
        #   0 = FAKE (AI generated by Stable Diffusion v1.4)
        #   1 = REAL (photographs from CIFAR-10)
        # Always verify label mappings — they vary by dataset and are
        # a common source of accidentally training an inverted classifier.
        if label == 1 and real_count < max_samples_per_class:
            img.save(real_dir / f"real_{real_count:05d}.jpg")
            real_count += 1
        elif label == 0 and ai_count < max_samples_per_class:
            img.save(ai_dir / f"ai_{ai_count:05d}.jpg")
            ai_count += 1

        if (real_count + ai_count) % 500 == 0:
            print(f"  Downloaded: {real_count} real, {ai_count} AI...", end="\r")

    print(f"\nDone. Saved {real_count} real and {ai_count} AI images to {output_dir}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=str, default="./raw_data",
                        help="Directory to save downloaded images")
    parser.add_argument("--samples", type=int, default=5000,
                        help="Max images per class (default 5000)")
    args = parser.parse_args()

    download_cifake(Path(args.output), args.samples)

    print("\nNext step:")
    print("  python dataset_curator.py ./raw_data ./curated_data")
